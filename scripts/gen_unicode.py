import sys
import unicodedata

MAX = 0x110000

# The Unicode White_Space property (PropList.txt), which is what \s means to a Unicode regex engine.
WHITE_SPACE = (
    (0x09, 0x0D), (0x20, 0x20), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680), (0x2000, 0x200A),
    (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000),
)


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def cat0(prefix):
    return lambda cp: unicodedata.category(chr(cp)).startswith(prefix)


def in_white_space(cp):
    return any(lo <= cp <= hi for lo, hi in WHITE_SPACE)


def emit(name, rs):
    out = [f"const Range {name}[] = {{"]
    line = "   "
    for lo, hi in rs:
        item = " {0x%X,0x%X}," % (lo, hi)
        if len(line) + len(item) > 116:
            out.append(line)
            line = "   "
        line += item
    if line.strip():
        out.append(line)
    out.append("};")
    out.append(f"const size_t {name}Count = sizeof({name}) / sizeof({name}[0]);")
    return "\n".join(out)


def main():
    tables = [
        ("kLetter", ranges(cat0("L"))),
        ("kMark", ranges(cat0("M"))),
        ("kNumber", ranges(cat0("N"))),
        ("kSpace", ranges(in_white_space)),
    ]
    w = sys.stdout.write
    w("// GENERATED by scripts/gen_unicode.py — do not edit by hand.\n")
    w(f"// Unicode {unicodedata.unidata_version}.\n")
    w("// Classes: \\p{L}, \\p{M}, \\p{N} (general categories) and \\s (the White_Space property).\n")
    w('#include "limbo/unicode.hpp"\n\n')
    w("namespace limbo::uni {\n\n")
    for name, rs in tables:
        w(f"// {len(rs)} ranges\n")
        w(emit(name, rs))
        w("\n\n")
    w("}  // namespace limbo::uni\n")
    sys.stderr.write("unicode %s: %s\n" % (
        unicodedata.unidata_version, ", ".join(f"{n}={len(r)} ranges" for n, r in tables)))


if __name__ == "__main__":
    main()
