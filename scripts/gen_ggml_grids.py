"""Extract the ggml codebook grids into src/ggml_grids.cpp.

CLEANROOM.md §4: grids that must match bit for bit come from ggml under its MIT notice, or are
regenerated, and are listed in THIRD_PARTY_NOTICES. They are copied verbatim here — a grid is a fact,
not expression — while the dequantisation that reads them is Limbo's own code.

    python3 scripts/gen_ggml_grids.py [path/to/ggml-common.h] > src/ggml_grids.cpp

Only the four tables the ladder's formats need are emitted: the IQ2_S and IQ3_S codebooks, the sign
mask they share, and the IQ4_NL value table.
"""
import re
import sys

DEFAULT = "/home/alca/projects/llama.cpp/ggml/src/ggml-common.h"

# ggml table name -> (C++ name in limbo::quants, type)
WANTED = {
    "kmask_iq2xs": ("kIq2SignMask", "uint8_t"),
    "iq2s_grid": ("kIq2sGrid", "uint64_t"),
    "iq3s_grid": ("kIq3sGrid", "uint32_t"),
    "kvalues_iq4nl": ("kIq4NlValues", "int8_t"),
}


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    text = open(path, encoding="utf-8", errors="replace").read()

    tables = {}
    for m in re.finditer(r"GGML_TABLE_BEGIN\(\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*\)\s*\n(.*?)GGML_TABLE_END\(\)",
                         text, re.S):
        ctype, name, size, body = m.group(1), m.group(2), m.group(3), m.group(4)
        if name in WANTED:
            tables[name] = (ctype, size, body.strip())

    missing = [n for n in WANTED if n not in tables]
    if missing:
        sys.exit(f"gen_ggml_grids: not found in {path}: {', '.join(missing)}")

    w = sys.stdout.write
    w("// GENERATED by scripts/gen_ggml_grids.py — do not edit by hand.\n")
    w("//\n")
    w("// Codebook grids and sign masks for the ggml i-quant formats, copied verbatim from\n")
    w(f"// {path}\n")
    w("// (ggml, MIT). CLEANROOM.md §4: a grid that must match bit for bit is a fact and comes from\n")
    w("// ggml under its notice; the dequantisation that reads it is Limbo's own code. See\n")
    w("// THIRD_PARTY_NOTICES.\n")
    w('#include "limbo/quants.hpp"\n\n')
    w("namespace limbo::quants {\n\n")
    for gname, (cname, ctype) in WANTED.items():
        ctype_g, size, body = tables[gname]
        w(f"// ggml {gname}[{size}] ({ctype_g})\n")
        w(f"const {ctype} {cname}[{size}] = {{\n")
        for line in body.splitlines():
            line = line.strip()
            if line:
                w("    " + line + "\n")
        w("};\n\n")
    w("}  // namespace limbo::quants\n")
    sys.stderr.write(f"wrote {len(WANTED)} tables from {path}\n")


if __name__ == "__main__":
    main()
